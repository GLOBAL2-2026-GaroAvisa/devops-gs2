-- =====================================================================
-- GaroAvisa API - Global Solution 2026/2 (CitizenTech)
-- Script de banco de dados (DDL) - Oracle Database (servidor da FIAP)
--
-- Cria as 8 tabelas da API, com chaves primárias, chaves estrangeiras
-- e índices. É o mesmo modelo gerado pelas migrations do Entity
-- Framework Core (pasta GaroAvisa.Infrastructure/Migrations).
--
-- Ordem de criação: primeiro as tabelas sem dependência, depois as que
-- apontam para elas (USUARIO -> LOCAL -> ALERTA, PREVISAO, COMPROMISSO).
-- =====================================================================


-- ---------------------------------------------------------------------
-- 1. T_GS_USUARIO
-- Contas de acesso (perfil USUARIO ou ADMIN). A senha é guardada como
-- hash, nunca em texto.
-- ---------------------------------------------------------------------
CREATE TABLE T_GS_USUARIO (
    ID          NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    NOME        NVARCHAR2(100) NOT NULL,
    EMAIL       NVARCHAR2(150) NOT NULL,
    SENHA_HASH  NVARCHAR2(255) NOT NULL,
    TIPO        NVARCHAR2(20)  NOT NULL,
    DT_CRIACAO  TIMESTAMP(7)   NOT NULL,
    CONSTRAINT PK_T_GS_USUARIO PRIMARY KEY (ID)
);


-- ---------------------------------------------------------------------
-- 2. T_GS_LOCAL
-- Lugares da rotina do usuário (Casa, Trabalho, Escola...), com as
-- coordenadas usadas para buscar a previsão do tempo.
-- ---------------------------------------------------------------------
CREATE TABLE T_GS_LOCAL (
    ID               NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    ID_USUARIO       NUMBER(10)     NOT NULL,
    ETIQUETA         NVARCHAR2(60)  NOT NULL,
    NOME             NVARCHAR2(120) NOT NULL,
    ESTADO           NVARCHAR2(80),
    PAIS             NVARCHAR2(80),
    LATITUDE         BINARY_DOUBLE  NOT NULL,
    LONGITUDE        BINARY_DOUBLE  NOT NULL,
    FUSO             NVARCHAR2(60)  NOT NULL,
    PRINCIPAL        NUMBER(1)      NOT NULL,
    RECEBER_ALERTAS  NUMBER(1)      NOT NULL,
    DT_CRIACAO       TIMESTAMP(7)   NOT NULL,
    CONSTRAINT PK_T_GS_LOCAL PRIMARY KEY (ID),
    CONSTRAINT FK_T_GS_LOCAL_T_GS_USUARIO_ID_USUARIO
        FOREIGN KEY (ID_USUARIO) REFERENCES T_GS_USUARIO (ID) ON DELETE CASCADE
);

CREATE INDEX IX_T_GS_LOCAL_ID_USUARIO ON T_GS_LOCAL (ID_USUARIO);


-- ---------------------------------------------------------------------
-- 3. T_GS_PREFERENCIA
-- Preferências de notificação de cada usuário.
-- ---------------------------------------------------------------------
CREATE TABLE T_GS_PREFERENCIA (
    ID                     NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    ID_USUARIO             NUMBER(10)    NOT NULL,
    RESUMO_DIARIO_ATIVO    NUMBER(1)     NOT NULL,
    RESUMO_DIARIO_HORARIO  NVARCHAR2(5)  NOT NULL,
    ALERTAS_DO_DIA         NUMBER(1)     NOT NULL,
    PREVISAO_MUDOU         NUMBER(1)     NOT NULL,
    COMPROMISSOS           NUMBER(1)     NOT NULL,
    SILENCIO_NOTURNO       NUMBER(1)     NOT NULL,
    DT_ATUALIZACAO         TIMESTAMP(7)  NOT NULL,
    CONSTRAINT PK_T_GS_PREFERENCIA PRIMARY KEY (ID),
    CONSTRAINT FK_T_GS_PREFERENCIA_T_GS_USUARIO_ID_USUARIO
        FOREIGN KEY (ID_USUARIO) REFERENCES T_GS_USUARIO (ID) ON DELETE CASCADE
);

CREATE INDEX IX_T_GS_PREFERENCIA_ID_USUARIO ON T_GS_PREFERENCIA (ID_USUARIO);


-- ---------------------------------------------------------------------
-- 4. T_GS_REGRA_ALERTA
-- Regras definidas pelo administrador (tipo de risco, limite e
-- gravidade) que geram os alertas.
-- ---------------------------------------------------------------------
CREATE TABLE T_GS_REGRA_ALERTA (
    ID          NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    TIPO        NVARCHAR2(30)  NOT NULL,
    LIMITE      BINARY_DOUBLE  NOT NULL,
    GRAVIDADE   NVARCHAR2(10)  NOT NULL,
    TITULO      NVARCHAR2(100) NOT NULL,
    DESCRICAO   NVARCHAR2(300) NOT NULL,
    ATIVA       NUMBER(1)      NOT NULL,
    DT_CRIACAO  TIMESTAMP(7)   NOT NULL,
    CONSTRAINT PK_T_GS_REGRA_ALERTA PRIMARY KEY (ID)
);


-- ---------------------------------------------------------------------
-- 5. T_GS_ALERTA
-- Alertas criados para um local quando a previsão atinge uma regra.
-- ---------------------------------------------------------------------
CREATE TABLE T_GS_ALERTA (
    ID              NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    ID_LOCAL        NUMBER(10)     NOT NULL,
    DT_PREVISAO     TIMESTAMP(7)   NOT NULL,
    TIPO            NVARCHAR2(30)  NOT NULL,
    TITULO          NVARCHAR2(100) NOT NULL,
    DESCRICAO       NVARCHAR2(300) NOT NULL,
    GRAVIDADE       NVARCHAR2(10)  NOT NULL,
    VALOR_PREVISTO  BINARY_DOUBLE,
    LIDO            NUMBER(1)      NOT NULL,
    DT_CRIACAO      TIMESTAMP(7)   NOT NULL,
    CONSTRAINT PK_T_GS_ALERTA PRIMARY KEY (ID),
    CONSTRAINT FK_T_GS_ALERTA_T_GS_LOCAL_ID_LOCAL
        FOREIGN KEY (ID_LOCAL) REFERENCES T_GS_LOCAL (ID) ON DELETE CASCADE
);

CREATE INDEX IX_T_GS_ALERTA_ID_LOCAL ON T_GS_ALERTA (ID_LOCAL);


-- ---------------------------------------------------------------------
-- 6. T_GS_PREVISAO
-- Última previsão guardada de cada local, usada para avisar quando a
-- previsão muda de forma brusca.
-- ---------------------------------------------------------------------
CREATE TABLE T_GS_PREVISAO (
    ID              NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    ID_LOCAL        NUMBER(10)    NOT NULL,
    DT_PREVISAO     TIMESTAMP(7)  NOT NULL,
    CODIGO_TEMPO    NUMBER(10)    NOT NULL,
    TEMP_MAXIMA     BINARY_DOUBLE,
    TEMP_MINIMA     BINARY_DOUBLE,
    CHUVA_MM        BINARY_DOUBLE,
    PROB_CHUVA      NUMBER(10),
    RAJADA_VENTO    BINARY_DOUBLE,
    DT_ATUALIZACAO  TIMESTAMP(7)  NOT NULL,
    CONSTRAINT PK_T_GS_PREVISAO PRIMARY KEY (ID),
    CONSTRAINT FK_T_GS_PREVISAO_T_GS_LOCAL_ID_LOCAL
        FOREIGN KEY (ID_LOCAL) REFERENCES T_GS_LOCAL (ID) ON DELETE CASCADE
);

CREATE INDEX IX_T_GS_PREVISAO_ID_LOCAL ON T_GS_PREVISAO (ID_LOCAL);


-- ---------------------------------------------------------------------
-- 7. T_GS_COMPROMISSO
-- Compromissos do usuário em um dos seus locais (ex.: consulta,
-- reunião), com a previsão do dia.
-- ---------------------------------------------------------------------
CREATE TABLE T_GS_COMPROMISSO (
    ID              NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    ID_LOCAL        NUMBER(10)    NOT NULL,
    NOME            NVARCHAR2(80) NOT NULL,
    DT_COMPROMISSO  TIMESTAMP(7)  NOT NULL,
    DT_CRIACAO      TIMESTAMP(7)  NOT NULL,
    CONSTRAINT PK_T_GS_COMPROMISSO PRIMARY KEY (ID),
    CONSTRAINT FK_T_GS_COMPROMISSO_T_GS_LOCAL_ID_LOCAL
        FOREIGN KEY (ID_LOCAL) REFERENCES T_GS_LOCAL (ID) ON DELETE CASCADE
);

CREATE INDEX IX_T_GS_COMPROMISSO_ID_LOCAL ON T_GS_COMPROMISSO (ID_LOCAL);


-- ---------------------------------------------------------------------
-- 8. T_GS_IDEMPOTENCIA
-- Respostas guardadas por 24 horas para evitar registros duplicados
-- quando o mesmo pedido chega de novo (cabeçalho Idempotency-Key).
-- ---------------------------------------------------------------------
CREATE TABLE T_GS_IDEMPOTENCIA (
    ID               NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    CHAVE            NVARCHAR2(100)  NOT NULL,
    ID_USUARIO       NUMBER(10)      NOT NULL,
    ROTA             NVARCHAR2(200)  NOT NULL,
    HASH_REQUISICAO  NVARCHAR2(64)   NOT NULL,
    STATUS_CODE      NUMBER(10)      NOT NULL,
    RESPOSTA_JSON    NVARCHAR2(2000) NOT NULL,
    DT_CRIACAO       TIMESTAMP(7)    NOT NULL,
    CONSTRAINT PK_T_GS_IDEMPOTENCIA PRIMARY KEY (ID)
);


